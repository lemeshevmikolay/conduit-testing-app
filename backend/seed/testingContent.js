function sourceFor(index, concept) {
  if (index % 5 < 2) {
    return {
      name: "ISTQB CTFL v4.0.1",
      url: "https://istqb.org/wp-content/uploads/2024/11/ISTQB_CTFL_Syllabus_v4.0.1.pdf",
      tags: "istqb testing theory",
    };
  }
  if (index % 5 < 4) {
    return {
      name: "Habr",
      url: "https://habr.com/ru/search/?q=testing",
      tags: "habr testing qa",
    };
  }
  return {
    name: "Stack Overflow",
      url: "https://stackoverflow.com/search?q=software+testing",
    tags: "stackoverflow testing qa",
  };
}

const articles = concepts.flatMap(([concept, explanation], conceptIndex) =>
  angles.map(([angle, practice], angleIndex) => {
    const index = conceptIndex * angles.length + angleIndex;
    const source = sourceFor(index, concept);
    return {
      title: `${concept}: ${angle.toLowerCase()}`,
      description: `${explanation} У цьому матеріалі розглянуто аспект «${angle.toLowerCase()}» і спосіб застосувати його в тестовому процесі.`,
      tags: `${source.tags} ${conceptIndex % 2 ? "quality" : "software"}`,
      sourceName: source.name,
      sourceUrl: source.url,
      practice,
    };
  }),
);

module.exports = { authors, articles };
